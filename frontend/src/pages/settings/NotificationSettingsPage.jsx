import { useEffect, useState } from 'react'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { notificationSettingsApi } from '../../services/apis'
import { Badge, Button, Card, Field, PageHeader, Select } from '../../components/ui'
import { DataTable } from '../../components/tables/DataTable'
import { toast } from '../../store/toastStore'
import { formatDate } from '../../utils/format'
import { asArray } from '../../utils/collections'

const CHANNELS = [
  { key: 'inApp', label: 'In-app', hint: 'Bell icon inside the app', channel: null },
  { key: 'whatsapp', label: 'WhatsApp', hint: 'Message to the phone number', channel: 'WHATSAPP' },
  { key: 'sms', label: 'SMS', hint: 'Text message to the phone number', channel: 'SMS' },
  { key: 'email', label: 'E-mail', hint: 'Needs the tenant e-mail address', channel: 'EMAIL' },
]

const EVENTS = [
  ['payments', 'Payment verified or rejected', 'Tell the tenant what happened to their payment'],
  ['complaints', 'Complaints', 'Tell owner and managers about new ones, tenants about updates'],
  ['announcements', 'Announcements', 'Send every announcement to the tenants of that property'],
]

function Switch({ checked, onChange, label, hint, disabled }) {
  return (
    <label className={`flex cursor-pointer items-start justify-between gap-4 py-2.5 ${disabled ? 'opacity-50' : ''}`}>
      <span>
        <span className="block text-sm font-medium text-ink-950">{label}</span>
        {hint ? <span className="block text-xs text-ink-600">{hint}</span> : null}
      </span>
      <input
        type="checkbox"
        role="switch"
        className="mt-1 h-5 w-9 shrink-0 cursor-pointer accent-[var(--color-brand)]"
        checked={Boolean(checked)}
        disabled={disabled}
        onChange={(e) => onChange(e.target.checked)}
      />
    </label>
  )
}

const Section = ({ title, description, children }) => (
  <Card className="p-5">
    <h2 className="font-display text-xl text-ink-950">{title}</h2>
    {description ? <p className="mt-0.5 text-sm text-ink-600">{description}</p> : null}
    <div className="mt-3 divide-y divide-line">{children}</div>
  </Card>
)

export function NotificationSettingsPage() {
  const qc = useQueryClient()
  const query = useQuery({ queryKey: ['notification-settings'], queryFn: notificationSettingsApi.get })
  const logs = useQuery({ queryKey: ['message-logs'], queryFn: () => notificationSettingsApi.logs(50) })
  const [form, setForm] = useState(null)

  useEffect(() => {
    if (query.data?.settings) setForm(query.data.settings)
  }, [query.data])

  const providers = query.data?.providers || {}
  const lastRun = query.data?.lastRun

  const save = useMutation({
    mutationFn: () => {
      const { channels, rent, events, digest, autoMarkOverdue, autoGenerateDues } = form
      return notificationSettingsApi.update({
        channels: { inApp: channels.inApp, whatsapp: channels.whatsapp, sms: channels.sms, email: channels.email },
        rent: { enabled: rent.enabled, daysBefore: rent.daysBefore, onDueDay: rent.onDueDay, overdueEveryDays: rent.overdueEveryDays },
        events: { complaints: events.complaints, announcements: events.announcements, payments: events.payments },
        digest, autoMarkOverdue, autoGenerateDues,
      })
    },
    onSuccess: () => { toast.success('Notification settings saved.'); qc.invalidateQueries({ queryKey: ['notification-settings'] }) },
    onError: (e) => toast.error(e.message),
  })

  const test = useMutation({
    mutationFn: () => {
      const on = CHANNELS.filter((c) => c.channel && form.channels[c.key]).map((c) => c.channel)
      if (!on.length) throw new Error('Switch on WhatsApp, SMS or e-mail first.')
      return notificationSettingsApi.test({ channels: on })
    },
    onSuccess: (r) => {
      const rows = asArray(r?.results)
      toast.info(rows.length ? rows.map((x) => `${x.channel}: ${x.status.toLowerCase()}`).join(' · ') : 'Nothing was sent.')
      qc.invalidateQueries({ queryKey: ['message-logs'] })
    },
    onError: (e) => toast.error(e.message),
  })

  const run = useMutation({
    mutationFn: notificationSettingsApi.runNow,
    onSuccess: (r) => {
      const s = asArray(r?.summary)[0] || {}
      toast.success(`Done. ${s.markedOverdue ?? 0} marked overdue, ${s.remindersSent ?? 0} reminders sent.`)
      qc.invalidateQueries({ queryKey: ['notification-settings'] })
      qc.invalidateQueries({ queryKey: ['message-logs'] })
    },
    onError: (e) => toast.error(e.message),
  })

  if (!form) return <p className="text-sm text-ink-600">{query.isError ? query.error.message : 'Loading…'}</p>

  const set = (path, value) =>
    setForm((f) => {
      const next = structuredClone(f)
      const keys = path.split('.')
      let o = next
      keys.slice(0, -1).forEach((k) => { o = o[k] })
      o[keys.at(-1)] = value
      return next
    })

  const toggleDay = (d) => {
    const days = form.rent.daysBefore.includes(d) ? form.rent.daysBefore.filter((x) => x !== d) : [...form.rent.daysBefore, d]
    set('rent.daysBefore', days.sort((a, b) => b - a))
  }

  return (
    <div className="mx-auto grid max-w-3xl gap-5">
      <PageHeader
        title="Notifications & reminders"
        description="Choose how tenants, managers and you are told about rent, complaints and announcements."
        actions={<Button loading={save.isPending} onClick={() => save.mutate()}>Save settings</Button>}
      />

      <Section title="Channels" description="Where messages are sent. WhatsApp, SMS and e-mail need a provider set up on the server.">
        {CHANNELS.map((c) => {
          const live = !c.channel || providers[c.channel] !== 'console'
          return (
            <div key={c.key} className="flex items-center justify-between gap-3">
              <div className="flex-1">
                <Switch checked={form.channels[c.key]} onChange={(v) => set(`channels.${c.key}`, v)} label={c.label} hint={c.hint} />
              </div>
              {c.channel ? <Badge tone={live ? 'success' : 'warning'}>{live ? `Live · ${providers[c.channel]}` : 'Test mode'}</Badge> : null}
            </div>
          )
        })}
        <div className="flex flex-wrap items-center justify-between gap-3 pt-3">
          <p className="text-xs text-ink-600">Test mode only prints messages in the server log. Nothing reaches a phone yet.</p>
          <Button variant="secondary" size="sm" loading={test.isPending} onClick={() => test.mutate()}>Send a test message to me</Button>
        </div>
      </Section>

      <Section title="Rent reminders" description="Sent every day at 9 am to tenants who still owe rent.">
        <Switch checked={form.rent.enabled} onChange={(v) => set('rent.enabled', v)} label="Send rent reminders" />
        <div className="py-3">
          <p className="text-sm font-medium text-ink-950">Remind before the due date</p>
          <div className="mt-2 flex flex-wrap gap-2">
            {[1, 2, 3, 5, 7].map((d) => (
              <button
                key={d}
                type="button"
                disabled={!form.rent.enabled}
                onClick={() => toggleDay(d)}
                className={`rounded-full border px-3.5 py-1.5 text-sm transition ${form.rent.daysBefore.includes(d) ? 'border-brand bg-brand-soft font-semibold text-brand' : 'border-line text-ink-600 hover:border-ink-300'}`}
              >
                {d} day{d > 1 ? 's' : ''} before
              </button>
            ))}
          </div>
        </div>
        <Switch checked={form.rent.onDueDay} onChange={(v) => set('rent.onDueDay', v)} label="Remind on the due date" disabled={!form.rent.enabled} />
        <div className="py-3">
          <Field label="After the due date, repeat the reminder every">
            <Select value={form.rent.overdueEveryDays} disabled={!form.rent.enabled} onChange={(e) => set('rent.overdueEveryDays', Number(e.target.value))}>
              {[1, 2, 3, 5, 7].map((d) => <option key={d} value={d}>{d === 1 ? 'day' : `${d} days`}</option>)}
            </Select>
          </Field>
        </div>
      </Section>

      <Section title="Events" description="Messages sent the moment something happens.">
        {EVENTS.map(([key, label, hint]) => (
          <Switch key={key} checked={form.events[key]} onChange={(v) => set(`events.${key}`, v)} label={label} hint={hint} />
        ))}
        <Switch checked={form.digest} onChange={(v) => set('digest', v)} label="Daily summary for the owner" hint="Overdue rent, payments to verify and open complaints, every morning" />
      </Section>

      <Section title="Automation" description="Housekeeping done by the daily task.">
        <Switch checked={form.autoMarkOverdue} onChange={(v) => set('autoMarkOverdue', v)} label="Mark unpaid rent as overdue" hint="After the due date passes with nothing paid" />
        <Switch checked={form.autoGenerateDues} onChange={(v) => set('autoGenerateDues', v)} label="Create this month's rent dues automatically" hint="From every active rent plan, so you never forget to generate them" />
        <div className="flex flex-wrap items-center justify-between gap-3 pt-3">
          <p className="text-xs text-ink-600">
            {lastRun ? `Last run ${formatDate(lastRun.startedAt)}: ${lastRun.summary?.remindersSent ?? 0} reminders, ${lastRun.summary?.markedOverdue ?? 0} marked overdue.` : 'The daily task has not run yet.'}
          </p>
          <Button variant="secondary" size="sm" loading={run.isPending} onClick={() => run.mutate()}>Run daily tasks now</Button>
        </div>
      </Section>

      <div>
        <h2 className="mb-3 font-display text-xl text-ink-950">Message history</h2>
        <DataTable
          loading={logs.isLoading}
          rows={asArray(logs.data)}
          emptyTitle="No messages yet"
          emptyDescription="Sent, skipped and failed messages show up here."
          columns={[
            { key: 'createdAt', header: 'When', render: (m) => formatDate(m.createdAt) },
            { key: 'type', header: 'Type', render: (m) => String(m.type).replaceAll('_', ' ').toLowerCase() },
            { key: 'channel', header: 'Channel' },
            { key: 'to', header: 'To', render: (m) => m.tenant?.name || m.to || '—' },
            { key: 'status', header: 'Status', render: (m) => <Badge tone={m.status === 'SENT' ? 'success' : m.status === 'FAILED' ? 'danger' : 'warning'} title={m.error || ''}>{m.status}</Badge> },
          ]}
        />
      </div>
    </div>
  )
}
