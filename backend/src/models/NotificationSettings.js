import mongoose from 'mongoose'

// One document per organisation: which channels are on and when reminders go out.
const notificationSettingsSchema = new mongoose.Schema(
  {
    organization: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Organization',
      required: true,
      unique: true,
    },

    channels: {
      inApp: { type: Boolean, default: true },
      whatsapp: { type: Boolean, default: false },
      sms: { type: Boolean, default: false },
      email: { type: Boolean, default: false },
    },

    rent: {
      enabled: { type: Boolean, default: true },
      // Days before the due date on which a reminder is sent.
      daysBefore: { type: [Number], default: [3, 1] },
      onDueDay: { type: Boolean, default: true },
      // After the due date a reminder repeats every N days.
      overdueEveryDays: { type: Number, default: 3, min: 1, max: 30 },
    },

    events: {
      complaints: { type: Boolean, default: true },
      announcements: { type: Boolean, default: true },
      payments: { type: Boolean, default: true },
    },

    digest: { type: Boolean, default: true },

    // Housekeeping done by the daily job.
    autoMarkOverdue: { type: Boolean, default: true },
    autoGenerateDues: { type: Boolean, default: false },
  },
  { timestamps: true }
)

export const DEFAULT_SETTINGS = new mongoose.Document({}, notificationSettingsSchema).toObject()

export default mongoose.model('NotificationSettings', notificationSettingsSchema)
