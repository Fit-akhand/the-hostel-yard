import { z } from 'zod'

const bool = z.boolean().optional()

export const updateNotificationSettingsSchema = z.object({
  channels: z.object({ inApp: bool, whatsapp: bool, sms: bool, email: bool }).strict().optional(),
  rent: z.object({
    enabled: bool,
    daysBefore: z.array(z.number().int().min(1).max(15)).max(5).optional(),
    onDueDay: bool,
    overdueEveryDays: z.number().int().min(1).max(30).optional(),
  }).strict().optional(),
  events: z.object({ complaints: bool, announcements: bool, payments: bool }).strict().optional(),
  digest: bool,
  autoMarkOverdue: bool,
  autoGenerateDues: bool,
}).strict()

export const testMessageSchema = z.object({
  channels: z.array(z.enum(['WHATSAPP', 'SMS', 'EMAIL'])).optional(),
})
